   '''legend'',coalesce(p.legend,false),''tier'',p.tier,''age'',p.age,''nat'',p.nat,''bt'',case when p.tier=''bigtime'' then public.on_bt_json(p.src) end,');
 end if;
end $$;

-- ─────────────────────────────────────────────────────────────────────────────
-- Loja: caixas
-- ─────────────────────────────────────────────────────────────────────────────
create or replace function public.on_pack_gate() returns boolean language sql stable security definer set search_path=public as $$
 select auth.uid() is not null and (coalesce(public.is_admin(),false) or coalesce((select public_open from public.on_config),false)) $$;

create or replace function public.on_pack_left(p_item public.on_pack_items,p_user uuid,p_club int) returns int
language sql stable security definer set search_path=public as $$
 select case when p_item.kind='bigtime' and exists(select 1 from public.on_players o where o.club_id=p_club and o.src=p_item.ref) then 0
  when p_item.kind='player' and exists(select 1 from public.on_players o where o.club_id=p_club and o.src=p_item.src) then 0
  else greatest(0,p_item.balls-(select count(*) from public.on_pack_draws d where d.item_id=p_item.id and d.user_id=p_user))::int end $$;

create or replace function public.on_pool_json(p_src text) returns jsonb language sql stable security definer set search_path=public as $$
 select jsonb_build_object('src',q.id,'name',q.name,'pos',q.pos,'ovr',round(q.rating),'age',q.age,'nat',q.nat) from public.on_pool q where q.id=p_src $$;

-- p_admin: com quantidades e chances (painel). Para o técnico: só o que tem na caixa e o que já é dele, sem números.
create or replace function public.on_pack_json(k public.on_packs,p_user uuid,p_club int,p_admin boolean default false) returns jsonb
language sql stable security definer set search_path=public as $$
 select jsonb_build_object('id',k.id,'title',k.title,'subtitle',k.subtitle,'price',k.price,'starts_at',k.starts_at,'ends_at',k.ends_at,'status',k.status,
  'empty',coalesce((select sum(public.on_pack_left(i,p_user,p_club)) from public.on_pack_items i where i.pack_id=k.id),0)=0,
  'total',case when p_admin then (select sum(i.balls) from public.on_pack_items i where i.pack_id=k.id) end,
  'items',coalesce((select jsonb_agg(jsonb_build_object('id',i.id,'kind',i.kind,'qty',i.qty,
     'balls',case when p_admin then i.balls end,
     'got',i.kind in('bigtime','player') and public.on_pack_left(i,p_user,p_club)=0,
     'bt',case when i.kind='bigtime' then public.on_bt_json(i.ref) end,
     'player',case when i.kind='player' then public.on_pool_json(i.src) end)
    order by (i.kind='bigtime') desc,(i.kind='player') desc,i.sort,i.id) from public.on_pack_items i where i.pack_id=k.id),'[]'))
$$;

-- Caixas abertas agora + diamantes da conta. Sem acesso: {enabled:false}.
create or replace function public.online_packs() returns jsonb
language plpgsql stable security definer set search_path=public as $$
declare k public.careers;c public.on_clubs;
begin
 if not public.on_pack_gate() then return jsonb_build_object('enabled',false);end if;
 select x.* into k from public.careers x where x.user_id=auth.uid() order by (x.status='active') desc,x.created_at desc limit 1;
 begin c:=public.on_me();exception when others then c:=null;end;
 return jsonb_build_object('enabled',true,'server_now',now(),'diamonds',coalesce(k.diamonds,0),'has_club',c.id is not null,
  'packs',coalesce((select jsonb_agg(public.on_pack_json(p,auth.uid(),c.id) order by p.ends_at)
   from public.on_packs p where p.status='live' and p.starts_at<=now() and p.ends_at>now()),'[]'));
end $$;

-- Uma tiragem: cobra os diamantes, sorteia entre o que ainda está na caixa deste técnico e entrega o prêmio.
create or replace function public.online_pack_draw(p_pack bigint) returns jsonb
language plpgsql security definer set search_path=public as $$
declare k public.careers;c public.on_clubs;pk public.on_packs;it public.on_pack_items;b public.on_bigtime;v_pid text;v_total int;v_pick int;v_item bigint;
begin
 if not public.on_pack_gate() then raise exception 'Loja indisponível';end if;
 c:=public.on_me(true);
 select * into pk from public.on_packs where id=p_pack and status='live' and starts_at<=now() and ends_at>now();
 if pk.id is null then raise exception 'Essa caixa não está mais disponível';end if;
 select x.* into k from public.careers x where x.user_id=auth.uid() order by (x.status='active') desc,x.created_at desc limit 1 for update;
 if k.id is null then raise exception 'Conta sem carreira';end if;
 if k.diamonds<pk.price then raise exception 'Diamantes insuficientes';end if;
 perform pg_advisory_xact_lock(hashtext('pack:'||auth.uid()::text));
 select sum(public.on_pack_left(i,auth.uid(),c.id)) into v_total from public.on_pack_items i where i.pack_id=pk.id;
 if coalesce(v_total,0)<=0 then raise exception 'Você já tirou tudo desta caixa';end if;
 v_pick:=floor(random()*v_total)::int;
 select q.id into v_item from(select z.id,z.n,sum(z.n) over(order by z.id) acc from(
   select i.id,public.on_pack_left(i,auth.uid(),c.id) n from public.on_pack_items i where i.pack_id=pk.id) z) q
  where q.n>0 and q.acc>v_pick order by q.acc limit 1;
 select * into it from public.on_pack_items where id=v_item;
 perform set_config('econ.reason','online_pack',true);
 perform set_config('econ.ref',pk.id::text,true);
 update public.careers set diamonds=diamonds-pk.price where id=k.id;
 if it.kind='coins' then update public.careers set coins=coins+it.qty where id=k.id;end if;
 perform set_config('econ.reason','',true);
 perform set_config('econ.ref','',true);
 if it.kind='bigtime' then
  select * into b from public.on_bigtime where id=it.ref;
  v_pid:=public.on_bt_grant(b.id,c.id);
  insert into public.on_news(club_id,kind,text,data) values(c.id,'market',
   format('Big Time: %s (%s × %s, %s) chegou ao seu elenco!',b.name,coalesce(b.team,''),b.opponent,extract(year from b.match_date)),
   jsonb_build_object('bigtime',b.id,'player',v_pid));
 elsif it.kind='player' then
  v_pid:=public.on_real_insert(it.src,c.id,
   (select min(n) from generate_series(1,99) n where n not in(select coalesce(x.number,0) from public.on_players x where x.club_id=c.id)),
   (select max(id) from public.on_seasons)+2);
 elsif it.kind='energy' then update public.on_clubs set train_energy=train_energy+it.qty where id=c.id;
 elsif it.kind='cash' then perform public.on_money(c.id,it.qty,'pack',pk.title);
 elsif it.kind='whistle' then
  insert into public.on_items(user_id,item,qty) values(auth.uid(),'golden_whistle',it.qty)
   on conflict(user_id,item) do update set qty=public.on_items.qty+excluded.qty;
 end if;
 insert into public.on_pack_draws(pack_id,item_id,user_id,club_id,price,player_id) values(pk.id,it.id,auth.uid(),c.id,pk.price,v_pid);
 return jsonb_build_object('prize',jsonb_build_object('kind',it.kind,'qty',it.qty,'player',v_pid,
   'bt',case when it.kind='bigtime' then public.on_bt_json(it.ref) end,
   'card',case when it.kind='player' then (select jsonb_build_object('id',p.id,'name',p.name,'pos',p.pos,'ovr',p.ovr,'pot',p.pot,'age',p.age,'nat',p.nat,
     'card',public.on_card(p.id,p.pos,p.level,p.g)) from public.on_players p where p.id=v_pid) end),'store',public.online_packs());
end $$;

-- Coloca a carta no elenco (fora da escalação, número livre).
create or replace function public.on_bt_grant(p_bt text,p_club int) returns text
language plpgsql security definer set search_path=public as $$
declare b public.on_bigtime;v_id text;
begin
 select * into b from public.on_bigtime where id=p_bt;
 if b.id is null then raise exception 'Carta não encontrada';end if;
 if exists(select 1 from public.on_players where club_id=p_club and src=b.id) then raise exception 'Você já tem essa carta';end if;
 insert into public.on_legend_profiles(id,style_off,style_def,ai_styles,traits) values(b.id,b.style_off,b.style_def,b.ai_styles,b.traits)
  on conflict(id) do update set style_off=excluded.style_off,style_def=excluded.style_def,ai_styles=excluded.ai_styles,traits=excluded.traits;
 insert into public.on_players(club_id,src,name,pos,sec,nat,age,level,pot,ovr,number,wage,contract_end,agg,disc,star,legend,tier)
 values(p_club,b.id,b.name,b.pos,array(select x from unnest(b.sec) x where x in(select code from public.sim_positions) and x<>b.pos),
  b.nat,b.age,coalesce(b.start_rating,b.rating-10),b.rating,coalesce(b.start_rating,b.rating-10),
  (select min(n) from generate_series(1,99) n where n not in(select coalesce(x.number,0) from public.on_players x where x.club_id=p_club)),
  public.on_wage(90),null,40+floor(public.sim_hash01(b.id||':agg')*30)::int,55+floor(public.sim_hash01(b.id||':disc')*35)::int,false,false,'bigtime')
 returning id into v_id;
 -- regularidade B garantida mesmo se o gatilho mudar
 update public.on_players set form='B' where id=v_id;
 return v_id;
end $$;

