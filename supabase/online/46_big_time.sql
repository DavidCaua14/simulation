create or replace function public.on_admin_only() returns void language plpgsql stable security definer set search_path=public as $$
begin if not coalesce(public.is_admin(),false) then raise exception 'Acesso restrito';end if;end $$;

create or replace function public.on_admin_log(p_action text,p_detail jsonb) returns void language plpgsql security definer set search_path=public as $$
begin
 if to_regclass('public.admin_actions') is not null then
  execute 'insert into public.admin_actions(admin_id,action,detail) values($1,$2,$3)' using auth.uid(),p_action,p_detail;
 end if;
exception when others then null;
end $$;

create or replace function public.admin_bt_list() returns jsonb language plpgsql stable security definer set search_path=public as $$
begin
 perform public.on_admin_only();
 return jsonb_build_object(
  'cards',coalesce((select jsonb_agg(public.on_bt_json(b.id)||jsonb_build_object('owners',(select count(*) from public.on_players o where o.src=b.id))
    order by b.created_at desc) from public.on_bigtime b),'[]'),
  'packs',coalesce((select jsonb_agg(public.on_pack_json(p,auth.uid(),null,true)||jsonb_build_object(
     'draws',(select count(*) from public.on_pack_draws d where d.pack_id=p.id),
     'diamonds',(select coalesce(sum(d.price),0) from public.on_pack_draws d where d.pack_id=p.id)) order by p.starts_at desc)
   from public.on_packs p),'[]'),
  'traits',(select jsonb_agg(jsonb_build_object('code',t.code,'name',t.name,'descr',t.descr) order by t.name) from public.on_traits t),
  'styles',(select jsonb_agg(jsonb_build_object('code',s.code,'kind',s.kind,'name',s.name,'descr',s.descr) order by s.kind,s.name) from public.on_styles s),
  'positions',(select jsonb_agg(code order by sort) from public.sim_positions));
end $$;

-- Cria ou edita uma carta (p.id vazio = nova). Devolve a carta.
create or replace function public.admin_bt_save(p jsonb) returns jsonb language plpgsql security definer set search_path=public as $$
declare v_id text:=nullif(p->>'id','');b public.on_bigtime;
begin
 perform public.on_admin_only();
 if coalesce(trim(p->>'name'),'')='' then raise exception 'Informe o nome';end if;
 if not exists(select 1 from public.sim_positions where code=p->>'pos') then raise exception 'Posição inválida';end if;
 if (p->>'rating')::int not between 106 and 115 then raise exception 'Overall máximo entre 106 e 115';end if;
 if coalesce((p->>'start_rating')::int,(p->>'rating')::int-10) not between 85 and (p->>'rating')::int then raise exception 'Overall inicial entre 85 e o máximo';end if;
 if coalesce(trim(p->>'opponent'),'')='' or nullif(p->>'match_date','') is null then raise exception 'Informe a data e o adversário da atuação';end if;
 if exists(select 1 from jsonb_array_elements_text(coalesce(p->'traits','[]')) t where t not in(select code from public.on_traits)) then raise exception 'Habilidade inválida';end if;
 if v_id is null then
  insert into public.on_bigtime(name,pos,rating,age,match_date,opponent) values(trim(p->>'name'),p->>'pos',(p->>'rating')::int,
   coalesce((p->>'age')::int,25),(p->>'match_date')::date,trim(p->>'opponent')) returning id into v_id;
 end if;
 update public.on_bigtime set name=trim(p->>'name'),full_name=nullif(trim(p->>'full_name'),''),pos=p->>'pos',
  sec=array(select x from jsonb_array_elements_text(coalesce(p->'sec','[]')) x where x in(select code from public.sim_positions) and x<>p->>'pos'),
  nat=coalesce(nullif(upper(trim(p->>'nat')),''),'BRA'),rating=(p->>'rating')::int,age=coalesce((p->>'age')::int,25),
  match_date=(p->>'match_date')::date,opponent=trim(p->>'opponent'),team=nullif(trim(p->>'team'),''),
  competition=nullif(trim(p->>'competition'),''),score=nullif(trim(p->>'score'),''),story=nullif(trim(p->>'story'),''),
  photo=nullif(trim(p->>'photo'),''),photo_pos=coalesce(p->'photo_pos','{"x":50,"y":20,"zoom":1}'),
  style_off=(select code from public.on_styles where code=p->>'style_off' and kind='off'),style_def=(select code from public.on_styles where code=p->>'style_def' and kind='def'),
  ai_styles=array(select x from jsonb_array_elements_text(coalesce(p->'ai_styles','[]')) x where x in(select code from public.on_styles where kind='ai')),
  traits=array(select x from jsonb_array_elements_text(coalesce(p->'traits','[]')) x limit 6),
  start_rating=coalesce((p->>'start_rating')::int,(p->>'rating')::int-10),
  active=coalesce((p->>'active')::boolean,true),updated_at=now()
 where id=v_id returning * into b;
 -- cartas já entregues acompanham a edição (nome, posição, habilidades, estilos e overall, mantendo o treino feito)
 insert into public.on_legend_profiles(id,style_off,style_def,ai_styles,traits) values(b.id,b.style_off,b.style_def,b.ai_styles,b.traits)
  on conflict(id) do update set style_off=excluded.style_off,style_def=excluded.style_def,ai_styles=excluded.ai_styles,traits=excluded.traits;
 update public.on_players set name=b.name,sec=b.sec,nat=b.nat,level=b.start_rating,pot=b.rating,
  ovr=public.on_ovr(b.start_rating,b.rating,g),traits=b.traits,
  style_off=coalesce(b.style_off,style_off),style_def=coalesce(b.style_def,style_def),ai_styles=b.ai_styles
 where src=b.id and tier='bigtime';
 perform public.on_admin_log('bigtime_save',jsonb_build_object('id',b.id,'name',b.name));
 return public.on_bt_json(b.id);
end $$;

-- Cria ou edita uma caixa com o conteúdo (p.items = [{kind, ref, qty, balls}]). Itens já sorteados não mudam de id.
create or replace function public.admin_pack_save(p jsonb) returns jsonb language plpgsql security definer set search_path=public as $$
declare v_id bigint:=nullif(p->>'id','')::bigint;x jsonb;i int:=0;
begin
 perform public.on_admin_only();
 if coalesce(trim(p->>'title'),'')='' then raise exception 'Informe o nome da caixa';end if;
 if (p->>'ends_at')::timestamptz<=(p->>'starts_at')::timestamptz then raise exception 'O fim precisa ser depois do início';end if;
 if jsonb_array_length(coalesce(p->'items','[]'))=0 then raise exception 'A caixa precisa de pelo menos um prêmio';end if;
 if not exists(select 1 from jsonb_array_elements(p->'items') e where e->>'kind'='bigtime') then raise exception 'Coloque pelo menos uma carta Big Time';end if;
 if exists(select 1 from jsonb_array_elements(p->'items') e where e->>'kind'='bigtime'
   and not exists(select 1 from public.on_bigtime b where b.id=e->>'ref')) then raise exception 'Carta Big Time não encontrada';end if;
 if exists(select 1 from jsonb_array_elements(p->'items') e where e->>'kind'='player'
   and not exists(select 1 from public.on_pool q where q.id=e->>'src' and not q.legend)) then raise exception 'Carta base não encontrada';end if;
 if v_id is null then
  insert into public.on_packs(title,price,starts_at,ends_at) values(trim(p->>'title'),(p->>'price')::int,(p->>'starts_at')::timestamptz,(p->>'ends_at')::timestamptz)
  returning id into v_id;
  -- caixa nova tira a anterior da loja quando ela começa
  update public.on_packs set ends_at=(p->>'starts_at')::timestamptz
   where id<>v_id and status='live' and starts_at<(p->>'starts_at')::timestamptz and ends_at>(p->>'starts_at')::timestamptz;
 end if;
 update public.on_packs set title=trim(p->>'title'),subtitle=nullif(trim(p->>'subtitle'),''),price=(p->>'price')::int,
  starts_at=(p->>'starts_at')::timestamptz,ends_at=(p->>'ends_at')::timestamptz,status=coalesce(nullif(p->>'status',''),status) where id=v_id;
 -- prêmios sem tiragens podem sair; os outros só mudam a quantidade
 delete from public.on_pack_items it where it.pack_id=v_id
  and it.id not in(select (e->>'id')::bigint from jsonb_array_elements(p->'items') e where nullif(e->>'id','') is not null)
  and not exists(select 1 from public.on_pack_draws d where d.item_id=it.id);
 for x in select * from jsonb_array_elements(p->'items') loop
  i:=i+1;
  if nullif(x->>'id','') is not null then
   update public.on_pack_items set qty=greatest(1,coalesce((x->>'qty')::int,1)),balls=greatest(1,coalesce((x->>'balls')::int,1)),sort=i
   where id=(x->>'id')::bigint and pack_id=v_id;
  else
   insert into public.on_pack_items(pack_id,kind,ref,src,qty,balls,sort) values(v_id,x->>'kind',case when x->>'kind'='bigtime' then x->>'ref' end,
    case when x->>'kind'='player' then x->>'src' end,
    greatest(1,coalesce((x->>'qty')::int,1)),case when x->>'kind' in('bigtime','player') then 1 else greatest(1,coalesce((x->>'balls')::int,1)) end,i);
  end if;
 end loop;
 perform public.on_admin_log('pack_save',jsonb_build_object('id',v_id,'title',p->>'title'));
 return public.on_pack_json((select k from public.on_packs k where k.id=v_id),auth.uid(),null,true);
end $$;

-- Cartas base para a caixa: sorteio de n jogadores do catálogo (sem lendas) na faixa de overall, ou busca por nome.
create or replace function public.admin_pool_pick(p_n int,p_lo int,p_hi int,p_query text default null) returns jsonb
language plpgsql stable security definer set search_path=public as $$
begin
 perform public.on_admin_only();
 return coalesce((select jsonb_agg(public.on_pool_json(q.id)) from(
  select q.id from public.on_pool q where not q.legend and q.rating>=p_lo and q.rating<p_hi+1
   and (p_query is null or q.name ilike '%'||p_query||'%')
  order by case when p_query is null then random() else 0 end,q.rating desc limit least(greatest(p_n,1),200)) q),'[]');
end $$;

-- Aviso de caixa nova para cada técnico do modo Online (com o nome dele e o fim da caixa). Roda no tick.
create or replace function public.on_pack_notify(p_now timestamptz,p_new_day boolean) returns void
language plpgsql security definer set search_path=public as $$
declare pk public.on_packs;v_cards text;v_end text;
begin
 for pk in select * from public.on_packs where status='live' and notified_at is null and starts_at<=p_now and ends_at>p_now loop
  select string_agg(format('%s (%s%s, %s)',b.name,coalesce(b.team||' × ',''),b.opponent,extract(year from b.match_date)),' e ' order by i.sort)
   into v_cards from public.on_pack_items i join public.on_bigtime b on b.id=i.ref where i.pack_id=pk.id and i.kind='bigtime';
  v_end:=to_char(pk.ends_at at time zone 'America/Sao_Paulo','DD/MM "às" HH24:MI');
  if to_regclass('public.player_notices') is not null then
   execute 'insert into public.player_notices(career_id,kind,title,body)
    select k.id,''info'',$1,format(''%s, %s chegou à Loja: %s. Cartas vermelhas com overall acima de 105 que entram direto no seu elenco do modo Online. A caixa fica disponível até %s e depois sai da Loja.'',k.nickname,$2,$3,$4)
    from public.on_clubs c join lateral(select x.id,x.nickname from public.careers x where x.user_id=c.user_id order by (x.status=''active'') desc,x.created_at desc limit 1) k on true
    where c.user_id is not null and c.season_id=(select max(id) from public.on_seasons where status=''live'')
     and (coalesce((select public_open from public.on_config),false) or exists(select 1 from public.admins a where a.user_id=c.user_id))'
   using 'Big Time: '||coalesce(v_cards,pk.title),'a caixa “'||pk.title||'”',coalesce(v_cards,'atuações históricas'),v_end;
  end if;
  insert into public.on_news(club_id,kind,text,data)
  select c.id,'market',format('Caixa Big Time nova na Loja: %s. Disponível até %s.',coalesce(v_cards,pk.title),v_end),jsonb_build_object('pack',pk.id)
  from public.on_clubs c where c.user_id is not null and c.season_id=(select max(id) from public.on_seasons where status='live');
  update public.on_packs set notified_at=p_now where id=pk.id;
 end loop;
end $$;
update public.on_config set tick_hooks=array(select distinct x from unnest(tick_hooks||'on_pack_notify'::text) x);

