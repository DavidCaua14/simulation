-- MODO ONLINE — Fase 42: cartas BIG TIME e caixas da loja.
-- • Big Time: carta vermelha de uma atuação real (ex.: Ronaldinho contra o Real Madrid em 2005). Overall de 106 a 115,
--   regularidade sempre B, foto real, data, adversário, competição, placar, idade naquele dia e habilidades.
--   Os atributos passam do teto de 99 (até 99 + 70% do que o overall passa de 99), então ela pesa de verdade em campo.
--   Não pode ser vendida, não vai ao mercado e não vai para bots.
--   Chega com o overall inicial (start_rating) e o técnico treina até o máximo (rating), como as outras cartas.
-- • Caixas: o administrador cadastra pelo painel (período, preço em diamantes por tiragem e o conteúdo: Big Time, cartas
--   base e itens). Cada técnico tira sem reposição: o que saiu para ele sai da caixa dele; carta que o clube já tem não sai
--   de novo. Muitos prêmios na caixa e poucas Big Time: tirar as duas custa caro, como no eFootball. A loja não mostra
--   quantidades nem chances. Caixa nova tira a anterior da loja e avisa todos os técnicos (aviso com o nome de cada um).
-- • Elenco sem limite de jogadores.
-- • Fotos no Storage (bucket bigtime, público para leitura, gravação só do administrador).

create sequence if not exists public.on_bt_seq;
create table if not exists public.on_bigtime(
 id text primary key default 'bt-'||nextval('public.on_bt_seq'),
 name text not null,
 full_name text,
 pos text not null references public.sim_positions(code),
 sec text[] not null default '{}',
 nat text not null default 'BRA',
 rating smallint not null check (rating between 106 and 115),
 age smallint not null check (age between 15 and 45),      -- idade no dia da atuação
 match_date date not null,
 opponent text not null,
 team text,                                               -- clube ou seleção da época
 competition text,
 score text,                                              -- ex.: 3 x 0
 story text,
 photo text,                                              -- URL pública da foto
 photo_pos jsonb not null default '{"x":50,"y":20,"zoom":1}',
 style_off text,
 style_def text,
 ai_styles text[] not null default '{}',
 traits text[] not null default '{}',
 start_rating smallint,                                   -- overall com que a carta chega (treina até rating)
 active boolean not null default true,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
alter table public.on_bigtime add column if not exists start_rating smallint;
alter table public.on_bigtime enable row level security;
revoke all on public.on_bigtime from anon,authenticated;

create table if not exists public.on_packs(
 id bigint generated by default as identity primary key,
 title text not null,
 subtitle text,
 price int not null check (price between 1 and 10000),   -- diamantes por tiragem
 starts_at timestamptz not null,
 ends_at timestamptz not null check (ends_at>starts_at),
 status text not null default 'live' check (status in('draft','live','cancelled')),
 notified_at timestamptz,                                -- aviso de caixa nova já mandado
 created_at timestamptz not null default now()
);
alter table public.on_packs add column if not exists notified_at timestamptz;
create table if not exists public.on_pack_items(
 id bigint generated by default as identity primary key,
 pack_id bigint not null references public.on_packs(id) on delete cascade,
 kind text not null check (kind in('bigtime','player','energy','coins','cash','whistle')),
 ref text references public.on_bigtime(id),               -- carta, quando kind='bigtime'
 src text,                                                -- carta base do catálogo (on_pool.id), quando kind='player'
 qty int not null default 1 check (qty>0),                -- quantidade do prêmio (energia, moedas, dinheiro)
 balls smallint not null default 1 check (balls between 1 and 200), -- quantas vezes esse prêmio está na caixa
 sort smallint not null default 0
);
create index if not exists on_pack_items_pack on public.on_pack_items(pack_id);
create table if not exists public.on_pack_draws(
 id bigint generated by default as identity primary key,
 pack_id bigint not null references public.on_packs(id) on delete cascade,
 item_id bigint not null references public.on_pack_items(id) on delete cascade,
 user_id uuid not null,
 club_id int,
 price int not null,
 player_id text,
 at timestamptz not null default now()
);
create index if not exists on_pack_draws_user on public.on_pack_draws(user_id,pack_id);
alter table public.on_packs enable row level security;
alter table public.on_pack_items enable row level security;
alter table public.on_pack_draws enable row level security;
revoke all on public.on_packs,public.on_pack_items,public.on_pack_draws from anon,authenticated;

-- ─────────────────────────────────────────────────────────────────────────────
-- Motor: atributos da Big Time passam de 99
-- ─────────────────────────────────────────────────────────────────────────────
create or replace function public.on_attr_cap(p public.on_players) returns numeric language sql immutable set search_path=public as $$
 select case when p.tier='bigtime' then round(99+greatest(0,p.ovr-99)*.7,2) else 99 end::numeric $$;

-- on_comp com teto livre (mesma conta de on_comp, só muda o teto).
create or replace function public.on_comp_cap(p_id text,p_pos text,p_level numeric,p_g smallint[],p_cap numeric) returns numeric[]
language sql immutable set search_path=public as $$
 select array(
  select round(greatest(15,least(p_cap,
    case when k.i=5 and p_pos<>'GOL' then .7*p_level-32 else p_level+o.d[k.i] end
    +(public.sim_hash01(p_id||':a'||k.i)-.5)*6
    +coalesce(p_g[(array[3,2,1,2,0,3,1,4,4,1,4])[k.i]],0)))::numeric,2)
  from generate_series(1,11) k(i)
  cross join(select case p_pos
   when 'ATA' then array[0.5,-12.4,-22.7,-11.6,0,4.7,-0.9,-3.3,-8.9,-25.7,-1.7]
   when 'GOL' then array[-43.7,-24.3,-39.2,-23.6,1.1,-51,-33.3,-29.5,-19.3,-42.7,-10.9]
   when 'LD' then array[-8.6,-4.9,-2.3,-3.3,0,-19.5,-10.8,4.1,3.4,0.7,-6.1]
   when 'LE' then array[-9.4,-3.7,-2.2,-2.1,0,-20.8,-8.9,2.3,4.9,0.4,-5.2]
   when 'MC' then array[-7.8,2.0,-5.0,2.0,0,-11.8,-10.0,-6.5,2.1,-3.8,-4.2]
   when 'MEI' then array[-5.5,2.0,-17.0,0.8,0,-9.1,-16.9,-8.9,-4.4,-16.1,-7.2]
   when 'PD' then array[-0.3,-5.2,-18.7,-4.0,0,-5.7,-15.4,3.7,-1.6,-18.4,-9.1]
   when 'PE' then array[-1.2,-4.2,-19.8,-3.0,0,-7.0,-15.6,3.6,-1.4,-19.3,-6.9]
   when 'VOL' then array[-14.5,-4.2,0.4,-3.1,0,-19.5,-4.5,-9.6,-0.4,2.6,1.5]
   else array[-22.5,-13.2,1.8,-11.3,0,-30.8,1.4,-10.1,-5.1,2.6,-0.1] end::numeric[] d) o
  order by k.i)
$$;

create or replace function public.on_comp_skill(p public.on_players) returns numeric[] language sql stable set search_path=public as $$
 select array(select round(greatest(15,least(public.on_attr_cap(p),c[k.i]
   +coalesce((select sum((s.bump->>(array['att','cre','def','ctl','gk','fin','head','pace','stam','tack','str'])[k.i])::numeric)
     from public.on_styles s where s.code=any(p.ai_styles)),0)
   +coalesce((select sum((t.bump->>(array['att','cre','def','ctl','gk','fin','head','pace','stam','tack','str'])[k.i])::numeric)
     from public.on_traits t where t.code=any(p.traits)),0))),2)
  from generate_series(1,11) k(i) order by k.i)
 from(select case when p.tier='bigtime' then public.on_comp_cap(p.id,p.pos,p.ovr,'{0,0,0,0}'::smallint[],public.on_attr_cap(p))
   else public.on_comp(p.id,p.pos,p.level,p.g) end c) q $$;

create or replace function public.on_comp_now(p public.on_players) returns numeric[] language sql stable set search_path=public as $$
 select array(select round(greatest(15,least(public.on_attr_cap(p),x+public.on_arrow_delta(p.arrow))),2)
  from unnest(public.on_comp_skill(p)) with ordinality u(x,i) order by i) $$;

do $$ begin
 -- ficha mostra acima de 99
 if position('on_attr_cap' in pg_get_functiondef('public.on_sheet(on_players)'::regprocedure))=0 then
  perform public.on_patch('public.on_sheet(on_players)','greatest(30,least(99,round(v)))','greatest(30,least(ceil(public.on_attr_cap(p)),round(v)))');
 end if;
 -- regularidade B
 if position('bigtime' in pg_get_functiondef('public.on_player_profile_fill()'::regprocedure))=0 then
  perform public.on_patch('public.on_player_profile_fill()',
   '  new.form:=case when coalesce(new.legend,false) then ''B'' else ''C'' end;',
   '  new.form:=case when coalesce(new.legend,false) or new.tier=''bigtime'' then ''B'' else ''C'' end;');
 end if;
 -- não vende para o sistema
 if position('Big Time' in pg_get_functiondef('public.on_sell(text)'::regprocedure))=0 then
  perform public.on_patch('public.on_sell(text)',
   ' if p.id is null then raise exception ''Jogador fora do seu elenco'';end if;',
   ' if p.id is null then raise exception ''Jogador fora do seu elenco'';end if;
 if p.tier=''bigtime'' then raise exception ''Cartas Big Time não podem ser vendidas'';end if;');
 end if;
end $$;

