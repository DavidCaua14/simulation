-- MODO ONLINE — Fase 41: mercado com cópias, bots que compram e vendem, promoção relâmpago.
-- • O mesmo jogador pode estar em vários clubes (uma cópia por clube). Depois de comprado, ele volta ao mercado como
--   nova cópia passada a quarentena: base 7 dias, destaque (81+) 14 dias, lenda 21 dias. Destaques têm até 5 cópias
--   vendidas por temporada e lendas até 3 (on_config.copy_rules).
-- • Quem já tem o jogador não dá lance em outra cópia dele.
-- • Bots dão lance em cartas base e destaques (lendas continuam só para técnicos) quando o jogador vira titular ou
--   primeiro reserva da posição e cabe no caixa. Bot com elenco cheio anuncia o reserva que sobrou.
-- • Promoção relâmpago: algumas vezes por dia, dentro do horário do mercado, um lote de 30 minutos com lance inicial
--   30% menor e aviso para os técnicos. O mercado também garante lotes em todos os setores (goleiro, defesa, meio, ataque).

alter table public.on_config add column if not exists copy_rules jsonb not null
 default '{"base":{"days":7,"cap":0},"star":{"days":14,"cap":5},"legend":{"days":21,"cap":3}}'::jsonb;
alter table public.on_config add column if not exists flash_per_day smallint not null default 3;
alter table public.on_config add column if not exists flash_minutes smallint not null default 30;
alter table public.on_config add column if not exists flash_discount numeric not null default .7;
alter table public.on_lots add column if not exists flash_key text;
create unique index if not exists on_lots_flash on public.on_lots(flash_key) where flash_key is not null;

-- Uma cópia por clube (antes: uma no jogo inteiro).
drop index if exists public.on_players_src;
create unique index if not exists on_players_club_src on public.on_players(club_id,src) where src is not null and club_id is not null;
create index if not exists on_players_src_any on public.on_players(src) where src is not null;

-- Toda compra no mercado de jogador do catálogo (livre → clube) fica registrada: é o relógio da quarentena.
create table if not exists public.on_src_log(
 id bigint generated by default as identity primary key,
 src text not null,
 club_id int references public.on_clubs(id) on delete set null,
 season_id smallint,
 at timestamptz not null default now()
);
create index if not exists on_src_log_src on public.on_src_log(src,at desc);
alter table public.on_src_log enable row level security;
revoke all on public.on_src_log from anon,authenticated;

-- "Agora" do mercado: o tick informa o relógio (os laboratórios usam relógio simulado).
create or replace function public.on_mkt_now() returns timestamptz language sql stable set search_path=public as $$
 select coalesce(nullif(current_setting('on.now',true),'')::timestamptz,now()) $$;

create or replace function public.on_src_log_add() returns trigger language plpgsql security definer set search_path=public as $$
begin
 if new.src is not null and new.club_id is not null and old.club_id is null and coalesce(new.tier,'')<>'bigtime' then
  insert into public.on_src_log(src,club_id,season_id,at)
  values(new.src,new.club_id,(select k.season_id from public.on_clubs k where k.id=new.club_id),public.on_mkt_now());
 end if;
 return new;
end $$;
drop trigger if exists on_players_src_log on public.on_players;
create trigger on_players_src_log after update of club_id on public.on_players for each row execute function public.on_src_log_add();

-- Pode ir a leilão como nova cópia? (nenhuma cópia livre agora, quarentena cumprida e limite da temporada)
create or replace function public.on_src_free(p_src text,p_legend boolean,p_rating numeric) returns boolean
language sql stable security definer set search_path=public as $$
 select not exists(select 1 from public.on_players o where o.src=p_src and o.club_id is null)
  and coalesce((select max(g.at) from public.on_src_log g where g.src=p_src),'-infinity')
   <=public.on_mkt_now()-coalesce((r->>'days')::int,7)*interval '1 day'
  and (coalesce((r->>'cap')::int,0)=0 or (select count(*) from public.on_src_log g
   where g.src=p_src and g.season_id=(select max(id) from public.on_seasons where status='live'))<(r->>'cap')::int)
 from(select cfg.copy_rules->(case when p_legend then 'legend' when p_rating>=81 then 'star' else 'base' end) r from public.on_config cfg) q
$$;

-- Catálogo: no mercado (on.copies=1) vale a regra das cópias; montagem de elenco continua só com quem não tem dono.
create or replace function public.on_real_pick(p_pos text,p_lo numeric,p_hi numeric,p_seed text,p_legend boolean default false) returns text
language sql stable security definer set search_path=public as $$
 select p.id from public.on_pool p
 where p.legend=p_legend and (p_pos is null or p.pos=p_pos) and p.rating>=p_lo and p.rating<p_hi
  and case when current_setting('on.copies',true)='1' then public.on_src_free(p.id,p.legend,p.rating)
   else not exists(select 1 from public.on_players o where o.src=p.id) end
 order by public.sim_hash01(p_seed||':'||p.id) limit 1
$$;

do $$ begin
 if position('on_src_free' in pg_get_functiondef('public.on_gen_base(text,integer,text)'::regprocedure))=0 then
  perform public.on_patch('public.on_gen_base(text,integer,text)',
   '  and not exists(select 1 from public.on_players o where o.src=p.id)',
   '  and public.on_src_free(p.id,p.legend,p.rating)');
 end if;
end $$;

-- Bot: teto de lance (0 = não quer). Quer só quem vira titular ou primeiro reserva da posição, sem ter o jogador,
-- com elenco abaixo de 26 e sem dívida. Teto: base 50%–90% do valor; destaque 100%–160% do lance inicial;
-- nunca mais de 40% do caixa livre.
create or replace function public.on_bot_limit(p_club int,p_lot bigint,p_player text) returns bigint
language sql stable security definer set search_path=public as $$
 select case
  when p.tier='bigtime' or p.legend then 0
  when c.debt>0 or c.user_id is not null then 0
  when p.src is not null and exists(select 1 from public.on_players q where q.club_id=p_club and q.src=p.src) then 0
  when (select count(*) from public.on_players q where q.club_id=p_club)>=26 then 0
  when p.ovr<(select coalesce(avg(x.ovr),60)-6 from(select q.ovr from public.on_players q where q.club_id=p_club order by q.ovr desc limit 11) x) then 0 -- fraco demais
  when (select count(*) from public.on_players q where q.club_id=p_club and q.pos=p.pos and q.ovr>=p.ovr)
   >=case when p.pos in('ZAG','MC','ATA') then 3 else 2 end then 0      -- não seria titular nem primeiro reserva
  when public.sim_hash01('botwant:'||p_lot||':'||p_club)>=.45 then 0 -- este clube não entrou nessa disputa
  else least(floor((c.cash-c.reserved)*.4),
   case when p.level>=81 then round(public.on_start_price(p)*(1+.6*public.sim_hash01('botcap:'||p_lot||':'||p_club)))
    else round(public.on_value(p.ovr,p.age,p.pot)*(.50+.40*public.sim_hash01('botcap:'||p_lot||':'||p_club))) end)::bigint end
 from public.on_players p,public.on_clubs c
 where p.id=p_player and c.id=p_club
$$;
revoke all on function public.on_bot_limit(int,bigint,text) from public,anon,authenticated;

-- Lance: quem já tem o jogador não compra outra cópia; bots entram em destaques (lendas seguem só para técnicos).
do $$ begin
 if position('Você já tem' in pg_get_functiondef('public.on_bid_as(integer,bigint,bigint,timestamp with time zone)'::regprocedure))=0 then
  perform public.on_patch('public.on_bid_as(integer,bigint,bigint,timestamp with time zone)',
   ' if l.featured>=8 and exists(select 1 from public.on_clubs b where b.id=p_club and b.user_id is null) then raise exception ''Destaque e lenda são só para técnicos'';end if;',
   ' if l.featured=8 and exists(select 1 from public.on_clubs b where b.id=p_club and b.user_id is null) then raise exception ''Lendas são só para técnicos'';end if;
 if exists(select 1 from public.on_players o join public.on_players q on q.src=o.src and q.club_id=p_club where o.id=l.player_id and o.src is not null and q.id<>o.id) then
  raise exception ''Você já tem esse jogador no elenco'';
 end if;');
 end if;
 -- Big Time não vai ao mercado
 if position('Big Time' in pg_get_functiondef('public.on_lot_create(text,bigint)'::regprocedure))=0 then
  perform public.on_patch('public.on_lot_create(text,bigint)',
   ' if p.id is null then raise exception ''Jogador fora do seu elenco'';end if;',
   ' if p.id is null then raise exception ''Jogador fora do seu elenco'';end if;
 if p.tier=''bigtime'' then raise exception ''Cartas Big Time não podem ser vendidas'';end if;');
 end if;
 -- lote: relâmpago, se eu já tenho o jogador e o tipo da carta
 if position('''flash''' in pg_get_functiondef('public.on_lot_json(on_lots,integer)'::regprocedure))=0 then
  perform public.on_patch('public.on_lot_json(on_lots,integer)',
   '''featured'',l.featured,',
   '''featured'',l.featured,''flash'',l.featured=7,''tier'',p.tier,
  ''owned'',p.src is not null and exists(select 1 from public.on_players q where q.club_id=p_me and q.src=p.src and q.id<>p.id),');
 end if;
end $$;

-- Lote do sistema na hora (relâmpago e reposição de setor).
create or replace function public.on_lot_new(p_season int,p_player text,p_featured int,p_price bigint,p_now timestamptz,p_end timestamptz,
 p_hard timestamptz,p_key text default null) returns bigint
language sql security definer set search_path=public as $$
 insert into public.on_lots(season_id,player_id,start_price,opens_at,ends_at,hard_end,featured,flash_key)
 values(p_season,p_player,greatest(500,p_price),p_now,p_end,p_hard,p_featured,p_key) returning id $$;

-- Relâmpago, setores vazios, lances e anúncios dos bots. Roda a cada minuto depois do tick antigo do mercado.
create or replace function public.on_market_buzz(p_now timestamptz,p_new_day boolean) returns void
language plpgsql security definer set search_path=public as $$
declare s public.on_seasons;cfg public.on_config;v_close timestamptz;v_open timestamptz;v_at timestamptz;v_end timestamptz;
 v_key text;i int;pid text;p public.on_players;g record;r record;k int;v_bid bigint;v_lot bigint;v_epoch bigint:=floor(extract(epoch from p_now))::bigint;
begin
 select * into s from public.on_seasons where status='live';
 if s.id is null or not public.on_market_open(p_now) then return;end if;
 select * into cfg from public.on_config;
 perform set_config('on.now',p_now::text,true);
 perform set_config('on.copies','1',true);
 v_close:=(public.on_market_hours(p_now)->>'closes_at')::timestamptz;
 v_open:=v_close-((cfg.market_close*60+cfg.market_close_min-cfg.market_open*60)*interval '1 minute');

 -- 1. Promoção relâmpago: horários sorteados por dia, cada um vale por 10 minutos para começar
 for i in 1..cfg.flash_per_day loop
  v_at:=v_open+interval '20 minutes'+greatest(interval '0',v_close-v_open-interval '70 minutes')
   *public.sim_hash01(s.seed||':flash:'||(v_open at time zone 'America/Sao_Paulo')::date||':'||i);
  continue when p_now<v_at or p_now>=v_at+interval '10 minutes';
  v_key:=to_char(v_open at time zone 'America/Sao_Paulo','YYYYMMDD')||':'||i;
  continue when exists(select 1 from public.on_lots x where x.flash_key=v_key);
  if public.sim_hash01(s.seed||':flk:'||v_key)<.35 then
   pid:=public.on_gen_special(s.seed||':fl:'||v_key,false,null);
  end if;
  if pid is null then pid:=public.on_gen_base(s.seed||':fl:'||v_key,1+floor(public.sim_hash01(s.seed||':flt:'||v_key)*3)::int,null);end if;
  select * into p from public.on_players where id=pid;
  v_end:=least(p_now+cfg.flash_minutes*interval '1 minute',v_close);
  perform public.on_lot_new(s.id,pid,7,round(public.on_start_price(p)*cfg.flash_discount)::bigint,p_now,v_end,v_end+interval '15 minutes',v_key);
  insert into public.on_news(club_id,kind,text,data)
  select c.id,'market',format('Promoção relâmpago: %s (%s, %s) com lance inicial %s%% menor por %s minutos.',
    p.name,p.pos,round(p.ovr),round((1-cfg.flash_discount)*100),cfg.flash_minutes),jsonb_build_object('flash',v_key,'player',p.id)
  from public.on_clubs c where c.season_id=s.id and c.user_id is not null;
  pid:=null;
 end loop;

 -- 2. Todo setor com lote aberto (goleiro 1, defesa/meio/ataque 2)
 v_end:=least(p_now+interval '60 minutes',v_close);
 if v_end>=p_now+interval '20 minutes' then
  for g in select * from(values('GOL','{GOL}'::text[],1),('DEF','{LD,ZAG,LE}',2),('MEI','{VOL,MC,MEI}',2),('ATA','{PD,PE,ATA}',2)) v(k,ps,n) loop
   continue when(select count(*) from public.on_lots x join public.on_players q on q.id=x.player_id
    where x.season_id=s.id and x.status='open' and x.opens_at<=p_now and q.pos=any(g.ps))>=g.n;
   pid:=public.on_gen_base(s.seed||':min:'||g.k||':'||v_epoch,3+floor(public.sim_hash01(s.seed||':mint:'||g.k||v_epoch)*2)::int,
    g.ps[1+floor(public.sim_hash01(s.seed||':minp:'||g.k||v_epoch)*cardinality(g.ps))::int]);
   select * into p from public.on_players where id=pid;
   perform public.on_lot_new(s.id,pid,6,public.on_start_price(p),p_now,v_end,v_end+cfg.lot_extend_max);
  end loop;
 end if;

 -- 3. Lances dos bots nos 10 minutos finais (base, reposição, relâmpago e destaque). Disputa com técnico: mais chance.
 for r in select l.* from public.on_lots l
  where l.season_id=s.id and l.status='open' and l.featured<>8 and l.opens_at<=p_now and l.ends_at>p_now and l.ends_at<=p_now+interval '10 minutes'
   and(l.best_club is null or exists(select 1 from public.on_clubs h where h.id=l.best_club and h.user_id is not null))
   and random()<case when l.best_club is null then .12 else .35 end
  order by l.ends_at limit 20 loop
  v_bid:=public.on_min_bid((select x from public.on_lots x where x.id=r.id));
  select c.id into k from public.on_clubs c where c.season_id=s.id and c.user_id is null and c.id is distinct from r.seller
   and c.cash-c.reserved>=v_bid and public.on_bot_limit(c.id,r.id,r.player_id)>=v_bid
   order by random() limit 1;
  continue when k is null;
  begin perform public.on_bid_as(k,r.id,v_bid,p_now);exception when others then null;end;
 end loop;

 -- 4. Bot com elenco cheio anuncia o pior da posição mais cheia (no máximo 2 por minuto)
 if v_close-p_now>=interval '70 minutes' then
  for r in select c.id club,(select q.id from public.on_players q where q.club_id=c.id and q.tier is distinct from 'bigtime'
     and q.pos=(select x.pos from public.on_players x where x.club_id=c.id group by x.pos order by count(*) desc,x.pos limit 1)
     and not exists(select 1 from public.on_lots y where y.player_id=q.id and y.status='open')
     order by q.ovr,q.id limit 1) pid
   from public.on_clubs c where c.season_id=s.id and c.user_id is null and random()<.15
    and (select count(*) from public.on_players x where x.club_id=c.id)>=25
    and not exists(select 1 from public.on_lots y where y.seller=c.id and y.status='open')
   limit 2 loop
   continue when r.pid is null or public.on_in_live(r.pid);
   select * into p from public.on_players where id=r.pid;
   v_end:=p_now+cfg.user_lot_minutes*interval '1 minute';
   insert into public.on_lots(season_id,player_id,seller,start_price,opens_at,ends_at,hard_end)
   values(s.id,p.id,r.club,greatest(500,round(public.on_value(p.ovr,p.age,p.pot)*.6))::bigint,p_now,v_end,v_end+cfg.lot_extend_max);
  end loop;
 end if;
 perform set_config('on.copies','',true);
 perform set_config('on.now','',true);
end $$;
revoke all on function public.on_market_buzz(timestamptz,boolean),public.on_lot_new(int,text,int,bigint,timestamptz,timestamptz,timestamptz,text),
 public.on_src_free(text,boolean,numeric),public.on_src_log_add(),public.on_mkt_now() from public,anon,authenticated;

-- Cartas base do tick antigo também seguem a regra das cópias (só enquanto o mercado está aberto; desliga no fim).
do $$ begin
 if position('on.copies' in pg_get_functiondef('public.on_market_tick(timestamp with time zone,boolean)'::regprocedure))=0 then
  perform public.on_patch('public.on_market_tick(timestamp with time zone,boolean)',
   ' if not public.on_market_open(p_now) then return;end if; -- mercado fechado',
   ' if not public.on_market_open(p_now) then return;end if; -- mercado fechado
 perform set_config(''on.now'',p_now::text,true);
 perform set_config(''on.copies'',''1'',true);');
  perform public.on_patch('public.on_market_tick(timestamp with time zone,boolean)',
   '  begin perform public.on_bid_as(k,r.id,v_bid,p_now);exception when others then null;end;
 end loop;',
   '  begin perform public.on_bid_as(k,r.id,v_bid,p_now);exception when others then null;end;
 end loop;
 perform set_config(''on.copies'','''',true);
 perform set_config(''on.now'','''',true);');
 end if;
end $$;
update public.on_config set tick_hooks=array(select distinct x from unnest(tick_hooks||'on_market_buzz'::text) x);

