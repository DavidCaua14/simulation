-- MODO ONLINE — Fase 1: esquema, criação da temporada e escolha dos 3 craques.
--
-- Mundo compartilhado e separado do modo Temporadas: nada aqui usa career_id nem mgr_lock().
-- Uma temporada "ao vivo" por vez; 12 clubes (usuários + bots); liga em turno e returno com um jogo por
-- clube por dia, cada jogo do dia em um horário diferente.
--
-- Acesso: RLS ligado e sem policies em todas as tabelas on_*; o app só chama as funções abaixo.
-- Trava: sempre por linha (o clube do usuário), nunca uma trava global.
-- Custo: leituras pequenas (um clube, uma tabela de 12 linhas, 132 jogos); nenhuma função percorre o catálogo.

