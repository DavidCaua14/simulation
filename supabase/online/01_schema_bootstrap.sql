-- 19 jogadores genéricos do clube (com os 3 craques, o elenco fecha em 22). Uma única instrução.
create or replace function public.on_gen_squad(p_club int,p_seed text,p_base int,p_contract_end int) returns void
language sql security definer set search_path=public as $$
 insert into public.on_players(club_id,name,pos,age,level,pot,ovr,number,wage,contract_end,agg,disc)
 select p_club,public.cw_regen_name('BRA',x.s),x.pos,a.age,a.lvl,
  least(92,a.lvl+floor(public.sim_hash01(x.s||':pot')*case when a.age<24 then 12 else 5 end)::int),
  a.lvl,x.n,public.on_wage(a.lvl),p_contract_end+floor(public.sim_hash01(x.s||':ct')*2)::int,
  35+floor(public.sim_hash01(x.s||':agg')*40)::int,40+floor(public.sim_hash01(x.s||':disc')*45)::int
 from(select u.n::int n,u.pos,p_seed||':g'||u.n s
  from unnest(array['GOL','LD','ZAG','ZAG','VOL','LE','PD','MC','ATA','MEI','PE','GOL','ZAG','LD','MC','LE','VOL','MEI','ATA']) with ordinality u(pos,n)) x
 cross join lateral(select 19+floor(public.sim_hash01(x.s||':age')*14)::int age,
  p_base-4+floor(public.sim_hash01(x.s||':lvl')*9)::int lvl) a
$$;

-- Opção de craque: passo 0 defesa, 1 meio-campo, 2 ataque; p_i de 1 a 3. Determinística pela semente.
create or replace function public.on_star(p_seed text,p_step int,p_i int)
returns table(name text,pos text,age int,level int,pot int)
language sql immutable set search_path=public as $$
 select public.cw_regen_name('BRA',k.s),
  (array['ZAG','LD','LE','VOL','MC','MEI','PD','ATA','PE'])[p_step*3+p_i],
  22+floor(public.sim_hash01(k.s||':age')*8)::int,
  78+floor(public.sim_hash01(k.s||':lvl')*5)::int,
  least(94,78+floor(public.sim_hash01(k.s||':lvl')*5)::int+floor(public.sim_hash01(k.s||':pot')*7)::int)
 from(select p_seed||':star'||p_step||':'||p_i s) k
$$;

-- Escalação automática: 4-3-3 (ou a formação já salva), melhor jogador disponível por vaga, 12 no banco.
create or replace function public.on_auto_lineup(p_club int,p_formation text default null) returns void
language plpgsql security definer set search_path=public as $$
declare f public.sim_formations;s jsonb;used text[]:='{}';v_slots jsonb:='{}';pid text;
begin
 select fm.* into f from public.sim_formations fm
  where fm.id=coalesce(p_formation,(select l.formation from public.on_lineups l where l.club_id=p_club),'4-3-3');
 if f.id is null then raise exception 'Formação inválida';end if;
 for s in select e.value from jsonb_array_elements(f.slots) e loop
  select p.id into pid from public.on_players p
   left join public.sim_position_fit ft on ft.from_pos=p.pos and ft.to_pos=s->>'pos'
   where p.club_id=p_club and p.id<>all(used)
   order by (p.inj_until is not null and p.inj_until>current_date),
    p.ovr*greatest(coalesce(ft.fit,.5),case when s->>'pos'=any(p.sec) then .97 else 0 end)*(.7+.3*p.cond/100.0) desc,p.id
   limit 1;
  if pid is null then raise exception 'Elenco insuficiente para escalar';end if;
  used:=used||pid;
  v_slots:=v_slots||jsonb_build_object(s->>'slot',pid);
 end loop;
 insert into public.on_lineups(club_id,formation,slots,bench,tactics)
 values(p_club,f.id,v_slots,array(select p.id from public.on_players p where p.club_id=p_club and p.id<>all(used) order by p.ovr desc,p.id limit 12),'{}')
 on conflict(club_id) do update set formation=excluded.formation,slots=excluded.slots,bench=excluded.bench,updated_at=now();
end $$;

