-- Quem pode jogar: 'allowed' já tem clube na temporada atual; 'queued' entra na próxima.
create table if not exists public.on_access(
 user_id uuid primary key,
 state text not null check (state in('allowed','queued')),
 queued_at timestamptz not null default now()
);

