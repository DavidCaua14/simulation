-- O usuário logado pode usar o modo? Aberto para todos, ou e-mail na lista de testes.
create or replace function public.on_gate() returns boolean
language sql stable security definer set search_path=public as $$
 select coalesce((select c.public_open or lower(btrim(coalesce(auth.jwt()->>'email','')))=any(c.testers) from public.on_config c),false)
$$;

-- Clube do usuário na temporada ao vivo. p_lock trava a linha (escritas).
create or replace function public.on_me(p_lock boolean default false) returns public.on_clubs
language plpgsql security definer set search_path=public as $$
declare c public.on_clubs;
begin
 if not public.on_gate() then raise exception 'O modo online ainda não está aberto para a sua conta';end if;
 select k.* into c from public.on_clubs k join public.on_seasons s on s.id=k.season_id and s.status='live'
  where k.user_id=auth.uid();
 if c.id is null then raise exception 'Você não participa da temporada online atual';end if;
 if p_lock then select k.* into c from public.on_clubs k where k.id=c.id for update;end if;
 return c;
end $$;

-- Situação do usuário no modo: fechado para a conta ('unavailable'), sem vaga, na fila ou jogando; clube e próximo jogo.
create or replace function public.on_status() returns jsonb
language plpgsql stable security definer set search_path=public as $$
declare v_uid uuid:=auth.uid();s public.on_seasons;c public.on_clubs;a text;
begin
 if v_uid is null then raise exception 'Entre na sua conta para jogar';end if;
 if not public.on_gate() then
  return jsonb_build_object('server_now',now(),'access','unavailable','season',null,'club',null,'next',null);
 end if;
 select x.* into s from public.on_seasons x where x.status='live';
 select x.state into a from public.on_access x where x.user_id=v_uid;
 if s.id is not null then select k.* into c from public.on_clubs k where k.season_id=s.id and k.user_id=v_uid;end if;
 return jsonb_build_object('server_now',now(),
  'access',case when c.id is not null then 'playing' when a is not null then 'queued' else 'none' end,
  'season',case when s.id is null then null else jsonb_build_object('id',s.id,'kind',s.kind,'starts_on',s.starts_on) end,
  'club',case when c.id is null then null else jsonb_build_object('id',c.id,'name',c.name,'short',c.short,'colors',c.colors,
   'cash',c.cash,'reserved',c.reserved,'draft_step',c.draft_step) end,
  'next',case when c.id is null then null else(select jsonb_build_object('id',f.id,'comp',f.comp,'round',f.round,'kickoff',f.kickoff,
    'status',f.status,'at_home',f.home=c.id,'opp',jsonb_build_object('id',o.id,'name',o.name,'short',o.short,'colors',o.colors,'bot',o.user_id is null))
   from public.on_fixtures f join public.on_clubs o on o.id=case when f.home=c.id then f.away else f.home end
   where f.season_id=s.id and f.status<>'done' and (f.home=c.id or f.away=c.id) order by f.kickoff limit 1) end);
end $$;

-- Novo usuário pede vaga: entra na fila e joga a partir da próxima temporada.
create or replace function public.on_join_queue() returns jsonb
language plpgsql security definer set search_path=public as $$
begin
 if auth.uid() is null then raise exception 'Entre na sua conta para jogar';end if;
 if not public.on_gate() then raise exception 'O modo online ainda não está aberto para a sua conta';end if;
 insert into public.on_access(user_id,state) values(auth.uid(),'queued') on conflict(user_id) do nothing;
 return public.on_status();
end $$;

-- Escolha dos craques: passo atual, as 3 opções da linha e os craques já escolhidos.
create or replace function public.on_draft_read() returns jsonb
language plpgsql stable security definer set search_path=public as $$
declare c public.on_clubs:=public.on_me();v_seed text;
begin
 select s.seed||':'||c.id into v_seed from public.on_seasons s where s.id=c.season_id;
 return jsonb_build_object('step',c.draft_step,'done',c.draft_step>=3,
  'line',(array['DEF','MID','ATT'])[c.draft_step+1],
  'options',case when c.draft_step>=3 then '[]'::jsonb else(select jsonb_agg(jsonb_build_object('idx',i.i,'name',st.name,'pos',st.pos,
    'age',st.age,'ovr',st.level,'pot',st.pot,'value',public.on_value(st.level,st.age,st.pot)) order by i.i)
   from generate_series(1,3) i(i) cross join lateral public.on_star(v_seed,c.draft_step,i.i) st) end,
  'picked',coalesce((select jsonb_agg(jsonb_build_object('id',p.id,'name',p.name,'pos',p.pos,'age',p.age,'ovr',p.ovr,'pot',p.pot) order by p.number)
   from public.on_players p where p.club_id=c.id and p.star),'[]'::jsonb));
end $$;

-- Escolhe a opção p_idx do passo p_step. Repetir a chamada do mesmo passo (duplo clique) não escolhe duas vezes.
create or replace function public.on_draft_pick(p_step int,p_idx int) returns jsonb
language plpgsql security definer set search_path=public as $$
declare c public.on_clubs:=public.on_me(true);v_seed text;
begin
 if p_idx is null or p_idx not between 1 and 3 then raise exception 'Opção inválida';end if;
 if c.draft_step=p_step and c.draft_step<3 then
  select s.seed||':'||c.id into v_seed from public.on_seasons s where s.id=c.season_id;
  insert into public.on_players(club_id,name,pos,age,level,pot,ovr,number,wage,contract_end,star)
  select c.id,st.name,st.pos,st.age,st.level,st.pot,st.level,21+c.draft_step,public.on_wage(st.level),c.season_id+2,true
  from public.on_star(v_seed,c.draft_step,p_idx) st;
  update public.on_clubs set draft_step=draft_step+1 where id=c.id;
  if c.draft_step=2 then perform public.on_auto_lineup(c.id);end if;
 end if;
 return public.on_draft_read();
end $$;

-- Elenco, escalação e táticas do clube do usuário.
create or replace function public.on_squad() returns jsonb
language plpgsql stable security definer set search_path=public as $$
declare c public.on_clubs:=public.on_me();
begin
 return jsonb_build_object(
  'club',jsonb_build_object('id',c.id,'name',c.name,'short',c.short,'colors',c.colors,'cash',c.cash,'reserved',c.reserved),
  'players',coalesce((select jsonb_agg(jsonb_build_object('id',p.id,'name',p.name,'pos',p.pos,'sec',p.sec,'age',p.age,'ovr',p.ovr,'pot',p.pot,
    'cond',p.cond,'number',p.number,'wage',p.wage,'contract_end',p.contract_end,'star',p.star,'g',p.g,
    'injured',p.inj_until is not null and p.inj_until>current_date,'value',public.on_value(p.ovr,p.age,p.pot))
    order by sp.sort,p.ovr desc,p.id)
   from public.on_players p join public.sim_positions sp on sp.code=p.pos where p.club_id=c.id),'[]'::jsonb),
  'lineup',(select jsonb_build_object('formation',l.formation,'slots',l.slots,'bench',l.bench,'tactics',l.tactics)
   from public.on_lineups l where l.club_id=c.id));
end $$;

create or replace function public.on_lineup_save(p_formation text,p_slots jsonb,p_bench text[],p_tactics jsonb default null) returns jsonb
language plpgsql security definer set search_path=public as $$
declare c public.on_clubs:=public.on_me(true);f public.sim_formations;v_ids text[];v_bench text[]:=coalesce(p_bench,'{}');
begin
 if c.draft_step<3 then raise exception 'Escolha seus três craques antes de escalar';end if;
 select fm.* into f from public.sim_formations fm where fm.id=p_formation;
 if f.id is null then raise exception 'Formação inválida';end if;
 if jsonb_typeof(p_slots) is distinct from 'object' or (select count(*) from jsonb_object_keys(p_slots))<>11
  or exists(select 1 from jsonb_array_elements(f.slots) e where not p_slots ? (e->>'slot')) then
  raise exception 'Escalação incompleta: preencha as 11 vagas';
 end if;
 v_ids:=array(select e.value from jsonb_each_text(p_slots) e)||v_bench;
 if cardinality(v_bench)>12 then raise exception 'O banco aceita até 12 jogadores';end if;
 if cardinality(v_ids)<>(select count(distinct x) from unnest(v_ids) x) then raise exception 'Jogador repetido na escalação';end if;
 if exists(select 1 from unnest(v_ids) x where not exists(select 1 from public.on_players p where p.id=x and p.club_id=c.id)) then
  raise exception 'Jogador fora do seu elenco';
 end if;
 insert into public.on_lineups(club_id,formation,slots,bench,tactics)
 values(c.id,f.id,p_slots,v_bench,public.mgr_tactics_clean(coalesce(p_tactics,'{}'::jsonb)))
 on conflict(club_id) do update set formation=excluded.formation,slots=excluded.slots,bench=excluded.bench,
  tactics=case when p_tactics is null then public.on_lineups.tactics else excluded.tactics end,updated_at=now();
 return public.on_squad();
end $$;

create or replace function public.on_lineup_auto(p_formation text default null) returns jsonb
language plpgsql security definer set search_path=public as $$
declare c public.on_clubs:=public.on_me(true);
begin
 if c.draft_step<3 then raise exception 'Escolha seus três craques antes de escalar';end if;
 perform public.on_auto_lineup(c.id,p_formation);
 return public.on_squad();
end $$;

-- Nome do clube: de 3 a 24 caracteres, único na temporada.
create or replace function public.on_club_rename(p_name text) returns jsonb
language plpgsql security definer set search_path=public as $$
declare c public.on_clubs:=public.on_me(true);v text:=btrim(regexp_replace(coalesce(p_name,''),'\s+',' ','g'));
begin
 if char_length(v) not between 3 and 24 then raise exception 'O nome do clube precisa ter de 3 a 24 caracteres';end if;
 if exists(select 1 from public.on_clubs k where k.season_id=c.season_id and k.id<>c.id and lower(k.name)=lower(v)) then
  raise exception 'Já existe um clube com esse nome';
 end if;
 update public.on_clubs set name=v,short=upper(left(coalesce(nullif(regexp_replace(v,'[^A-Za-z0-9]','','g'),''),'CLB'),3)) where id=c.id;
 return public.on_status();
end $$;

-- Calendário da temporada: clubes e todos os jogos (132 de liga + copa). Mesma resposta para todos.
create or replace function public.on_calendar() returns jsonb
language plpgsql stable security definer set search_path=public as $$
declare c public.on_clubs:=public.on_me();
begin
 return jsonb_build_object('server_now',now(),'my_club',c.id,
  'clubs',(select jsonb_agg(jsonb_build_object('id',k.id,'name',k.name,'short',k.short,'colors',k.colors,'bot',k.user_id is null) order by k.id)
   from public.on_clubs k where k.season_id=c.season_id),
  'fixtures',coalesce((select jsonb_agg(jsonb_build_object('id',f.id,'comp',f.comp,'round',f.round,'stage',f.stage,'home',f.home,'away',f.away,
    'kickoff',f.kickoff,'status',f.status,'hg',f.hg,'ag',f.ag,'pens',f.pens) order by f.kickoff,f.id)
   from public.on_fixtures f where f.season_id=c.season_id),'[]'::jsonb));
end $$;

create or replace function public.on_standings() returns jsonb
language plpgsql stable security definer set search_path=public as $$
declare c public.on_clubs:=public.on_me();
begin
 return jsonb_build_object('my_club',c.id,'rows',(select jsonb_agg(jsonb_build_object('club_id',k.id,'name',k.name,'short',k.short,
    'colors',k.colors,'bot',k.user_id is null,'p',t.p,'w',t.w,'d',t.d,'l',t.l,'gf',t.gf,'ga',t.ga,'pts',t.pts)
    order by t.pts desc,t.gf-t.ga desc,t.gf desc,k.name)
   from public.on_table t join public.on_clubs k on k.id=t.club_id where t.season_id=c.season_id));
end $$;

