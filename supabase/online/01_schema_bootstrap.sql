-- Valor de mercado: 80 de nota ≈ 40 mil; dobra a cada 4,5 pontos; ajustado por idade e margem de evolução.
create or replace function public.on_value(p_ovr numeric,p_age numeric,p_pot numeric) returns bigint
language sql immutable set search_path=public as $$
 select round(greatest(250,40000*power(2,(least(p_ovr,99)-80)/4.5))
  *case when p_age<21 then 1.3 when p_age<24 then 1.2 when p_age<28 then 1 when p_age<31 then .8 when p_age<33 then .55 else .3 end
  *(1+greatest(0,p_pot-p_ovr)*.03))::bigint
$$;

-- Salário por dia de jogo.
create or replace function public.on_wage(p_ovr numeric) returns int
language sql immutable set search_path=public as $$
 select greatest(50,ceil(power(greatest(1,p_ovr-45),2)*.65+power(greatest(0,p_ovr-75),2)*12))::int
$$;

