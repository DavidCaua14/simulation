import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
// Gera a migração atômica da evolução 58 a partir de supabase/evolution/58_club_development.sql.
// Antes/depois compara, por carreira, as linhas de todas as tabelas existentes usando somente as colunas que já existiam:
// colunas novas (ex.: cw_players.retired_on) não contam como alteração; qualquer valor antigo diferente aborta a transação.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = process.argv[2] || path.join(root, 'supabase/migrations/20261104233000_club_development.sql')
const source = fs.readFileSync(path.join(root, 'supabase/evolution/58_club_development.sql'), 'utf8').replace(/^\s*(begin|commit);\s*$/gmi, '')
const header = `-- Generated by scripts/build-club-development.mjs; edit supabase/evolution/58_club_development.sql instead.
-- Atomic deployment: lock careers, compare protected rows per career (pre-existing columns only), retain all existing progress.
begin;
set local lock_timeout='5s';
set local statement_timeout='120s';
set local timezone='UTC';
create temporary table _dev_table_scopes on commit drop as
 select tab.table_name,array_agg(col.column_name::text order by col.column_name) cols from information_schema.tables tab
 join information_schema.columns col using(table_schema,table_name)
 where tab.table_schema='public' and tab.table_type='BASE TABLE' group by tab.table_name;
do $$ begin perform 1 from public.careers order by id for update;end $$;
create temporary table _dev_protected_before(career_id uuid,table_name text,predicate text,cols text[],n bigint,hash text,primary key(career_id,table_name)) on commit drop;
do $$ declare c record;t record;pred text;h text;n bigint;begin
 for c in select id from public.careers order by id loop
  for t in select * from _dev_table_scopes order by table_name loop
   pred:=case when t.table_name='careers' then 'id=$1' when 'career_id'=any(t.cols) then 'career_id=$1'
    when 'season_id'=any(t.cols) then 'season_id in(select id from public.career_seasons where career_id=$1)'
    when 'fixture_id'=any(t.cols) then 'fixture_id in(select f.id from public.season_fixtures f join public.career_seasons s on s.id=f.season_id where s.career_id=$1)' end;
   if pred is null then continue;end if;
   execute format('select count(*),md5(coalesce(string_agg(h,'''' order by h),'''')) from(select md5((select jsonb_object_agg(k,v) from jsonb_each(to_jsonb(x)) e(k,v) where k=any($2))::text) h from public.%I x where %s)z',t.table_name,pred) into n,h using c.id,t.cols;
   insert into _dev_protected_before values(c.id,t.table_name,pred,t.cols,n,h);
  end loop;
 end loop;
end $$;
`
const footer = `
do $$ declare r record;h text;n bigint;begin
 for r in select * from _dev_protected_before order by career_id,table_name loop
  execute format('select count(*),md5(coalesce(string_agg(h,'''' order by h),'''')) from(select md5((select jsonb_object_agg(k,v) from jsonb_each(to_jsonb(x)) e(k,v) where k=any($2))::text) h from public.%I x where %s)z',r.table_name,r.predicate) into n,h using r.career_id,r.cols;
  if n<>r.n or h<>r.hash then raise exception 'Protected progress differs in table %; deployment rolled back',r.table_name;end if;
 end loop;
 raise notice 'Protected progress verified for % careers, % table comparisons',(select count(distinct career_id) from _dev_protected_before),(select count(*) from _dev_protected_before);
end $$;
analyze public.cw_player_dev;analyze public.cw_player_pos_delta;analyze public.cw_training;analyze public.cw_facilities;analyze public.cw_staff;
notify pgrst,'reload schema';
commit;
`
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, header + source + footer)
console.log(`Built club development migration (${fs.statSync(target).size} bytes) into ${target}`)
