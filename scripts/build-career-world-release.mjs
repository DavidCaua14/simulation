import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
const root = resolve(import.meta.dirname, '..')
const files = ['24_career_world_schema.sql','25_career_world_calendar.sql','26_career_finance_contracts.sql','27_career_market.sql','28_career_jobs_news.sql','29_career_integration.sql','30_career_calendar_entry.sql','31_world_advance_speed.sql','32_squad_morale_contracts.sql','33_inbox.sql','34_ai_balance.sql','35_update_gift.sql']
const out = resolve(process.argv[2] || resolve(root, 'supabase/releases/carreira_completa.sql'))
const chunks = files.map(file => readFileSync(resolve(root,'supabase/evolution',file),'utf8').trim().replace(/^begin;\s*/i,'').replace(/\s*commit;\s*$/i,''))
const header = `-- Generated by scripts/build-career-world-release.mjs. Requires cartas_base.sql (21–23).
-- Review docs/CARREIRA_COMPLETA.md. Keep maintenance enabled. Transaction rolls back on error.
begin;
set local statement_timeout='90s';
select pg_advisory_xact_lock(hashtext('career-world-release-v1'));
set local lock_timeout='5s';
do $preflight$ begin
 if to_regprocedure('public.mgr_sync_base_cards(uuid)') is null or to_regclass('public.base_card_release') is null then raise exception 'Instale e valide cartas base (21–23) antes da carreira completa';end if;
 if exists(select 1 from public.career_seasons where mode in('coach','world') group by career_id,region,year having count(*)>1) then raise exception 'Histórico contém anos regionais duplicados; revise a prévia sem apagar resultados';end if;
 if exists(select 1 from public.user_cards u join public.cards c on c.id=u.card_id where c.tier<>'basica') or exists(select 1 from public.reward_boxes where status='pending') then raise exception 'Conclua a conversão das cartas especiais e caixas antes desta implantação';end if;
end $preflight$;
create temp table cw_protected_wallet on commit drop as select id,to_jsonb(c) as original from public.careers c;
create temp table cw_protected_results on commit drop as select id,to_jsonb(f) as original from public.season_fixtures f where status='played';
create temp table cw_protected_live on commit drop as select fixture_id,to_jsonb(m) as original from public.mgr_matches m where status='live';

`
mkdirSync(dirname(out),{recursive:true})
const verify = `
do $preserved$ begin
 if exists(select 1 from cw_protected_wallet b left join public.careers c using(id) where b.original is distinct from to_jsonb(c)) then raise exception 'A implantação alterou uma carreira existente';end if;
 if exists(select 1 from cw_protected_results b left join public.season_fixtures f using(id) where b.original is distinct from to_jsonb(f)) then raise exception 'A implantação alterou um resultado realizado';end if;
 if exists(select 1 from cw_protected_live b left join public.mgr_matches m using(fixture_id) where b.original is distinct from to_jsonb(m)) then raise exception 'A implantação alterou uma partida ao vivo';end if;
end $preserved$;
commit;
`
writeFileSync(out,header+chunks.join('\n\n')+verify)
console.log(out)
