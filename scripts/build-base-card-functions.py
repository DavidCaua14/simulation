"""Rebuild replacement functions from the repository's preceding migrations."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
latest={}
sources = list(sorted((ROOT/'supabase/seasons').glob('*.sql')))
sources += [p for p in sorted((ROOT/'supabase/manager').glob('*.sql')) if p.name!='06_cards_coach.sql']
sources += list(sorted((ROOT/'supabase/cards').glob('*.sql')))
sources += [ROOT/'supabase/manager/06_cards_coach.sql']
sources += list(sorted((ROOT/'supabase/evolution').glob('*.sql')))
for p in sources:
 if not p.name[:2].isdigit() or int(p.name[:2])>=21:continue
 source=p.read_text()
 for m in re.finditer(r'create\s+or\s+replace\s+function\s+public\.(\w+)\s*\(',source,re.I):
  rest=source[m.end():];body=re.search(r'\bas\s+(\$\w*\$)(.*?)\1\s*;',rest,re.I|re.S)
  if body:latest[m[1]]=source[m.start():m.end()+body.end()]
def once(s,old,new):
 if s.count(old)!=1:raise ValueError(f'Expected exactly one occurrence: {old[:100]!r}, got {s.count(old)}')
 return s.replace(old,new,1)
out=['-- Generated by scripts/build-base-card-functions.py. Run after 21.\nbegin;']
for name in ['mgr_lock','mgr_squad','mgr_match_payload','mgr_after_user_match','season_play','profile_build','refresh_wallet','streak_claim','streak_status_for','event_grant','admin_event_save','admin_events_list','card_discard']:
 s=latest[name]
 if name=='mgr_lock':s=once(s,'perform public.mgr_ensure(v_c);','perform public.mgr_ensure(v_c);\n  perform public.mgr_sync_base_cards(v_c.id);')
 elif name=='mgr_squad':s=once(s,"'id', p.id, 'name', p.full_name", "'club_id', mp.club_id, 'id', p.id, 'name', p.full_name")
 elif name=='mgr_match_payload':s=once(s,"'id', mp.player_id, 'name', p.short_name", "'club_id', case when mp.side='h' then f.home_club else f.away_club end, 'id', mp.player_id, 'name', p.short_name")
 elif name in ['mgr_after_user_match','season_play']:
  s,n=re.subn(r'v_xp\s*:= round\([^\n]+;', 'v_xp := 0;',s);assert n==1,(name,n)
  ref='p_fixture' if name=='mgr_after_user_match' else 'v_f.id'
  s,n=re.subn(r'v_coins\s*:= round\([^\n]+;',f'v_coins := coalesce((select coins from public.base_match_rewards where fixture_id={ref}),0);',s);assert n==1,(name,n)
  s,n=re.subn(r'  update public.careers set xp = xp \+ v_xp, coins = coins \+ v_coins where id = [^;]+;[^\n]*','  -- Account resources are credited once by base_fixture_reward.',s);assert n==1,(name,n)
  s=once(s,"'rewards', jsonb_build_object('xp', v_xp, 'coins', v_coins",f"'rewards', jsonb_build_object('energy', coalesce((select energy from public.base_match_rewards where fixture_id={ref}),0), 'xp', v_xp, 'coins', v_coins")
 elif name=='profile_build':
  s=s.replace('  v_card public.cards;\n','')
  a=s.index('  -- carta em destaque');b=s.index('  return jsonb_strip_nulls',a);s=s[:a]+s[b:]
  a=s.index("    'featured_card',");b=s.index("    'equipped',",a);s=s[:a]+s[b:]
  s=s.replace('where b.active and (p_full or pb.awarded_at is not null)','where (b.active or pb.awarded_at is not null) and (p_full or pb.awarded_at is not null)')
  s=s.replace('from public.cards where active)',"from public.cards where active and tier='basica')")
 elif name=='refresh_wallet':
  s=once(s,"'pending_boxes', (select count(*) from public.reward_boxes where career_id = v_c.id and status = 'pending'),", "'pending_boxes', 0,")
 elif name=='streak_claim':
  s,n=re.subn(r'  if v_r.box_tier is not null then[^\n]+\n','',s);assert n==1
  s=s.replace(", 'box_tier', v_r.box_tier",", 'energy', v_r.energy")
  s=once(s,"  update public.player_streaks set current","  if v_r.energy>0 then perform public.econ_apply(v_c.id,'bonus_energy',v_r.energy,'daily_streak',v_ref);end if;\n  update public.player_streaks set current")
 elif name=='streak_status_for':s=s.replace(", 'box_tier', box_tier",", 'energy', energy")
 elif name=='event_grant':
  a=s.index("    when 'box' then");b=s.index("    when 'cosmetic' then",a);s=s[:a]+s[b:]
  s=s.replace("  end case;", "    else raise exception 'Tipo de recompensa removido';\n  end case;")
 elif name=='admin_event_save':
  s=once(s,"    select * into v_kind from public.event_objective_kinds where id = o ->> 'kind';", "    if o->>'kind' in ('box_opened','card_collected','market_sale') then raise exception 'Objetivo removido';end if;\n    select * into v_kind from public.event_objective_kinds where id = o ->> 'kind';")
  s=s.replace("('coins', 'diamonds', 'energy', 'box', 'card', 'cosmetic', 'badge')","('coins', 'diamonds', 'energy', 'cosmetic', 'badge')")
  s='\n'.join(l for l in s.split('\n') if not ("if w ->> 'kind' = 'box'" in l or "if w ->> 'kind' = 'card'" in l))
 elif name=='admin_events_list':
  s=s.replace('from public.event_objective_kinds k)',"from public.event_objective_kinds k where k.id not in ('box_opened','card_collected','market_sale'))")
  s=s.replace('from public.card_tiers)',"from public.card_tiers where id='basica')")
