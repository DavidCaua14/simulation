import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
// Gera uma migração atômica a partir de um arquivo de supabase/evolution, com verificação de preservação por carreira.
// Uso: node scripts/build-release.mjs <evolution.sql> <migration.sql> [tabela_excluida ...]
// Tabelas excluídas são as que a migração compacta de propósito (limpeza); todas as demais tabelas com dados de carreira
// são comparadas antes/depois (somente colunas pré-existentes). Snapshot em tabela comum: funciona no SQL Editor.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const [src, target, ...excluded] = process.argv.slice(2)
if (!src || !target) throw new Error('Uso: node scripts/build-release.mjs <evolution.sql> <migration.sql> [tabelas excluídas]')
const body = fs.readFileSync(path.resolve(root, src), 'utf8').replace(/^\s*(begin|commit);\s*$/gmi, '')
const skip = ['_release_protected_before', ...excluded].map((t) => `'${t}'`).join(',')
const header = `-- Generated by scripts/build-release.mjs from ${src}; edit that file instead.
-- Paste the WHOLE file in the Supabase SQL Editor and run it at once.
-- Not compared (intentionally compacted): ${excluded.join(', ') || 'none'}.
begin;
set local lock_timeout='5s';
set local statement_timeout='300s';
set local timezone='UTC';
drop table if exists public._release_protected_before;
create table public._release_protected_before(career_id uuid,table_name text,predicate text,cols text[],n bigint,hash text,primary key(career_id,table_name));
alter table public._release_protected_before enable row level security;
revoke all on public._release_protected_before from public,anon,authenticated;
do $$ declare c record;t record;pred text;h text;n bigint;begin
 perform 1 from public.careers order by id for update;
 for c in select id from public.careers order by id loop
  for t in select tab.table_name::text table_name,array_agg(col.column_name::text order by col.column_name) cols
   from information_schema.tables tab join information_schema.columns col using(table_schema,table_name)
   where tab.table_schema='public' and tab.table_type='BASE TABLE' and tab.table_name not in(${skip})
   group by tab.table_name order by tab.table_name loop
   pred:=case when t.table_name='careers' then 'id=$1' when 'career_id'=any(t.cols) then 'career_id=$1'
    when 'season_id'=any(t.cols) then 'season_id in(select id from public.career_seasons where career_id=$1)'
    when 'fixture_id'=any(t.cols) then 'fixture_id in(select f.id from public.season_fixtures f join public.career_seasons s on s.id=f.season_id where s.career_id=$1)' end;
   if pred is null then continue;end if;
   execute format('select count(*),md5(coalesce(string_agg(h,'''' order by h),'''')) from(select md5((select jsonb_object_agg(k,v) from jsonb_each(to_jsonb(x)) e(k,v) where k=any($2))::text) h from public.%I x where %s)z',t.table_name,pred) into n,h using c.id,t.cols;
   insert into public._release_protected_before values(c.id,t.table_name,pred,t.cols,n,h);
  end loop;
 end loop;
end $$;
`
const footer = `
do $$ declare r record;h text;n bigint;begin
 if not exists(select 1 from public._release_protected_before) and exists(select 1 from public.careers) then
  raise exception 'Snapshot de preservação ausente; execute o arquivo inteiro de uma vez';
 end if;
 for r in select * from public._release_protected_before order by career_id,table_name loop
  execute format('select count(*),md5(coalesce(string_agg(h,'''' order by h),'''')) from(select md5((select jsonb_object_agg(k,v) from jsonb_each(to_jsonb(x)) e(k,v) where k=any($2))::text) h from public.%I x where %s)z',r.table_name,r.predicate) into n,h using r.career_id,r.cols;
  if n<>r.n or h<>r.hash then raise exception 'Protected progress differs in table %; deployment rolled back',r.table_name;end if;
 end loop;
 raise notice 'Protected progress verified for % careers, % table comparisons',(select count(distinct career_id) from public._release_protected_before),(select count(*) from public._release_protected_before);
end $$;
drop table public._release_protected_before;
notify pgrst,'reload schema';
commit;
`
fs.writeFileSync(path.resolve(root, target), header + body + footer)
console.log(`Built ${target} (${fs.statSync(path.resolve(root, target)).size} bytes)`)
